
# --- llm_helper.py: one shared LLM call 
# Read the API key and model from .env, send a prompt to the LLM through
# the Perplexity API, and return the JSON answer as a Python dictionary.
# Every answer is saved in data/llm_cache.json, so a rerun is free and provides the same result.

import json, os, hashlib #json is used to read/write the cache and turns the llm text answer into a Python dictionary, os talks to the Operating system to read the model name and API key; hashlib is used to create a unique key for each prompt
#hash the prompt to create a unique key for each prompt, so we can cache the answer and avoid asking the LLM again for the same promptl
from pathlib import Path
from dotenv import load_dotenv   
from perplexity import Perplexity 

BASE = Path(__file__).resolve().parent.parent      # the assignment folder
CACHE_PATH = BASE / "data" / "llm_cache.json"      #cache file path

# 1) Settings from .env
load_dotenv(BASE / ".env")
MODEL = os.getenv("LLM_MODEL", "anthropic/claude-haiku-5-5") 
API_KEY = os.getenv("PERPLEXITY_API_KEY")
if not API_KEY:
    raise SystemExit("Missing PERPLEXITY_API_KEY. Copy .env.example to .env and add your key.")

# max_retries=5: wait and retry automatically if we hit the rate limit 
#requests to the LLM can fail if we hit the rate limit, so we set max_retries=5 to wait and retry automatically
#Pepl Python SDK default is 2 and increasing to 5 supports up to 6 attempts (1 initial + 5 retries) before giving up. This is useful for large prompts that may take longer to process and may hit the rate limit.
client = Perplexity(api_key=API_KEY, max_retries=5)

# 2) Load the cache (answers from earlier runs)
if CACHE_PATH.exists():
    cache = json.loads(CACHE_PATH.read_text(encoding="utf-8"))
else:
    cache = {}


# 3) The one function the other scripts use  Max tokens were increased to 2000 to allow for longer responses from the LLM. This is useful for prompts that require more detailed answers or explanations, as it gives the model more space to generate a comprehensive response.
def ask_llm(instructions, prompt, schema, max_tokens=2000): #max tokens is required for Anthropic models, and we set it to 2000 to allow for longer responses from the LLM. This is useful for prompts that require more detailed answers or explanations, as it gives the model more space to generate a comprehensive response.
    """Send one prompt and return the JSON answer as a dictionary."""
    key_text = MODEL + instructions + prompt + json.dumps(schema) #When removing MODEL from the key_text, the cache will not differentiate between different models used for the same prompt and schema. This could lead to incorrect caching behavior, where an answer generated by one model is reused for a prompt intended for a different model. By including MODEL in the key_text, we ensure that the cache is specific to the model used, preventing potential mismatches and ensuring that the correct answer is retrieved for each unique combination of model, instructions, prompt, and schema.
    key = hashlib.sha256(key_text.encode("utf-8")).hexdigest()

    if key in cache:                       # already asked: reuse the answer
        return cache[key]

    # Ask up to 3 times. Sometimes the LLM writes words around the JSON,
    # or sends no JSON at all. We keep only the part from the first "{" to the last "}".
    #extract and parse the JSON from the LLM's response, which may include additional text or formatting. We look for the first "{" and the last "}" to isolate the JSON content, and then attempt to parse it. If parsing fails, we retry up to 3 times to get a valid JSON response.
    answer = None
    for attempt in range(3): #up to 3 attempts to get a valid JSON response from the LLM, as sometimes the LLM may include additional text or formatting around the JSON, or may not return any JSON at all. We extract the JSON content and attempt to parse it, retrying if necessary.
        response = client.responses.create( #API request to the LLM using the Perplexity client, sending the model, instructions, prompt, maximum output tokens, and response format (JSON schema) to get a structured response from the LLM.   
            model=MODEL,
            instructions=instructions,
            input=prompt,
            max_output_tokens=max_tokens,      # required for Anthropic models
            response_format={
                "type": "json_schema",
                "json_schema": {"name": "answer", "schema": schema},
            },
        )
        text = response.output_text.strip() #JSON boundaries are determined by finding the first "{" and the last "}" in the LLM's response text. We extract the substring between these boundaries and attempt to parse it as JSON. If parsing fails, we retry up to 3 times to get a valid JSON response.
        start = text.find("{")                 # -1 means "not found"
        end = text.rfind("}")
        if start != -1 and end > start:
            try:
                answer = json.loads(text[start:end + 1]) # Parse the isolated JSON content
                break                          # good JSON: stop asking
            except json.JSONDecodeError: #error handling for JSON parsing failures
                pass                           # broken JSON: ask again
        print("  LLM answer was not JSON (try", attempt + 1, "of 3):", repr(text[:200]))

    if answer is None: #after 3 failed attempts to get a valid JSON response from the LLM, we raise a SystemExit exception with an error message indicating that the LLM did not provide usable JSON. This stops the program and informs the user of the issue.
        raise SystemExit("Stopped: the LLM gave no usable JSON 3 times. See the answers printed above.")


    cache[key] = answer                    # save right away
    CACHE_PATH.write_text(json.dumps(cache, indent=2, ensure_ascii=False), encoding="utf-8") #ensure_ascii=False: allow non-ASCII characters in the JSON file, so we can store emojis and other Unicode characters without escaping them
    return answer