def graph_at(path):
    if not path.is_file():
        raise FileNotFoundError(f"Missing earlier pipeline output: {path}")
    g = Graph()
    g.parse(str(path), format="turtle")
    return g


def named_pairs(g):
    return sorted({(str(a), str(b)) for a, b in g.subject_objects(RDFS.subClassOf)
                   if isinstance(a, URIRef) and isinstance(b, URIRef) and a != b})


def declarations(g):
    return {(s, p, o) for s, p, o in g if p == RDF.type and o in DECL_TYPES}


def reachable(edges):
    parents = defaultdict(set)
    for a, b in edges:
        parents[a].add(b)
    found = set()
    for start in list(parents):
        visited, stack = set(), list(parents[start])
        while stack:
            x = stack.pop()
            if x in visited:
                continue
            visited.add(x)
            if x != start:
                found.add((start, x))
            stack.extend(parents[x] - visited)
    return found


def verify_split(source, train, valid):
    a, b, c = map(lambda g: set(named_pairs(g)), (source, train, valid))
    if not a or not b or not c or b & c or b | c != a:
        raise RuntimeError("Invalid source/train/validation named subclass partition")
    declared = declarations(source)
    if not declared or any(declared - declarations(g) for g in (train, valid)):
        raise RuntimeError("Class/property declarations not preserved")
    if c & reachable(b):
        raise RuntimeError("Validation contains train-reachable local subclass pairs")
    return sorted(b), sorted(c), {"source_pairs": len(a), "training_pairs": len(b),
                                 "validation_pairs": len(c),
                                 "validation_fraction": len(c) / len(a),
                                 "source_declarations_preserved": len(declared)}


def write_json(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp")
    temp.write_text(json.dumps(obj, indent=2, default=str) + "\n", encoding="utf-8")
    temp.replace(path)


def write_csv(path, rows, fields):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp")
    with temp.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fields)
        writer.writeheader()
        writer.writerows(rows)
    temp.replace(path)


def internal_dev_split(train_graph, all_train_pairs, seed, dev_fraction):
    """Deterministic development split; retain all non-held-out graph triples."""
    rng = random.Random(seed)
    options = list(all_train_pairs)
    rng.shuffle(options)
    target = max(3, round(len(options) * dev_fraction))
    chosen = set()
    remaining = set(all_train_pairs)
    for edge in options:
        if len(chosen) == target:
            break
        proposal = remaining - {edge}
        if edge in reachable(proposal):
            continue
        remaining.remove(edge)
        chosen.add(edge)
    if len(chosen) < 3:
        raise RuntimeError("Could not form at least three internal dev edges")
    g = Graph()
    for prefix, ns in train_graph.namespace_manager.namespaces():
        g.bind(prefix, ns)
    for triple in train_graph:
        g.add(triple)
    for a, b in chosen:
        g.remove((URIRef(a), RDFS.subClassOf, URIRef(b)))
    if set(named_pairs(g)) != remaining:
        raise RuntimeError("Internal development split failed")
    if declarations(train_graph) - declarations(g):
        raise RuntimeError("Internal development split removed declarations")
    g.serialize(destination=str(DEV_TTL), format="turtle")
    return sorted(remaining), sorted(chosen)


def load_definition_text(training_graph):
    texts = defaultdict(list)
    definition_predicates = ("definition", "description", "elucidation", "comment")
    for subj, pred, obj in training_graph:
        if not isinstance(subj, URIRef) or not isinstance(obj, Literal):
            continue
        name = str(pred).rsplit("/", 1)[-1].rsplit("#", 1)[-1].lower()
        if name in ("label", "preflabel") or any(key in name for key in definition_predicates):
            value = str(obj).strip()
            if value:
                texts[str(subj)].append(value)
    enhanced = {}
    if ENRICHED.is_file():
        with ENRICHED.open("r", newline="", encoding="utf-8-sig") as f:
            reader = csv.DictReader(f)
            if reader.fieldnames:
                keys = {key.strip().lower(): key for key in reader.fieldnames}
                uri_key = next((keys[k] for k in IRI_KEYS if k in keys), None)
                def_key = next((keys[k] for k in TEXT_KEYS if k in keys), None)
                if uri_key and def_key:
                    for row in reader:
                        iri = (row.get(uri_key) or "").strip()
                        value = (row.get(def_key) or "").strip()
                        if iri and value:
                            enhanced[iri] = value
                else:
                    print("WARNING: enriched CSV headers not recognized; using RDF labels/definitions")
    for iri, value in enhanced.items():
        texts[iri].append(value)
    return {iri: " ".join(parts) for iri, parts in texts.items()}, len(enhanced)


def semantic_features(class_index, texts, width=256):
    """Deterministic hashed TF-IDF vectors, no extra model downloads required."""
    docs = {}
    for iri in class_index:
        local = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", iri.rsplit("/", 1)[-1])
        raw = (texts.get(iri, "") + " " + local).lower()
        tokens = re.findall(r"[a-z][a-z0-9]{1,}", raw)
        docs[iri] = tokens
    df = Counter()
    for words in docs.values():
        df.update(set(words))
    features = torch.zeros((len(class_index), width), dtype=torch.float32)
    total = len(class_index)
    for iri, idx in class_index.items():
        counts = Counter(docs[iri])
        for token, count in counts.items():
            digest = hashlib.blake2b(token.encode("utf-8"), digest_size=8).digest()
            j = int.from_bytes(digest, "big") % width
            weight = math.log1p(count) * (1 + math.log((1 + total) / (1 + df[token])))
            features[idx, j] += weight
    return F.normalize(features, p=2, dim=1)


def _source_import_iris():
    """Cache identity depends on ontology import IRIs, not any ML output."""
    source = graph_at(TRAIN)
    return sorted({str(obj) for obj in source.objects(None, OWL.imports)
                   if isinstance(obj, URIRef)})


def _import_cache_valid(import_iris):
    if not IMPORT_SNAPSHOT.is_file() or not IMPORT_MANIFEST.is_file():
        return False
    try:
        manifest = json.loads(IMPORT_MANIFEST.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return False
    if not (manifest.get("cache_schema") == 1
            and manifest.get("direct_import_iris") == import_iris
            and IMPORT_SNAPSHOT.stat().st_size > 100):
        return False
    import hashlib
    actual_digest = hashlib.sha256(IMPORT_SNAPSHOT.read_bytes()).hexdigest()
    return manifest.get("snapshot_sha256") == actual_digest


def _generate_import_free_root(path):
    """Produce an exact local root graph with owl:imports removed.

    All original logical axioms remain; the imported axioms are added from the
    cached snapshot separately. Never use an import-free *source* as a substitute
    for the imports themselves.
    """
    import hashlib
    raw = path.read_bytes()
    fingerprint = hashlib.sha256(raw).hexdigest()[:24]
    destination = IMPORT_FREE_DIR / f"{fingerprint}.ttl"
    if destination.is_file():
        return destination
    graph = graph_at(path)
    imports_count = len(list(graph.triples((None, OWL.imports, None))))
    graph.remove((None, OWL.imports, None))
    IMPORT_FREE_DIR.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix(".tmp.ttl")
    graph.serialize(destination=str(temporary), format="turtle")
    check = graph_at(temporary)
    if set(check) != set(graph) or any(check.triples((None, OWL.imports, None))):
        temporary.unlink(missing_ok=True)
        raise RuntimeError("Import-free fold graph failed exact triple preservation")
    temporary.replace(destination)
    print(f"LOCAL ROOT: {path.name}; removed {imports_count} imports directives", flush=True)
    return destination


def _ensure_import_snapshot():
    """Resolve the full import closure once; reuse its exact axioms thereafter.

    On an already primed project, no remote ontology request is performed.
    The source ontology's own training axioms are explicitly excluded so the
    cache cannot reintroduce held-out edges in internal masked folds.
    """
    global _IMPORT_AXIOMS, _IMPORT_INFO
    if _IMPORT_AXIOMS is not None:
        return _IMPORT_AXIOMS, _IMPORT_INFO

    from mowl.datasets.base import PathDataset
    from org.semanticweb.owlapi.apibinding import OWLManager
    from org.semanticweb.owlapi.model import IRI
    from java.util import HashSet

    direct_imports = _source_import_iris()
    IMPORT_CACHE.mkdir(parents=True, exist_ok=True)

    if not _import_cache_valid(direct_imports):
        print("IMPORT CACHE: missing or outdated; resolving source imports ONCE", flush=True)
        try:
            # Only this initial bootstrap may contact remote ontology servers.
            base = PathDataset(str(TRAIN.resolve()))
            root_ontology = base.ontology
            closure_ontologies = list(root_ontology.getImportsClosure())
            root_id = root_ontology.getOntologyID()
            imported_axioms = HashSet()
            imported_count = 0
            for ontology in closure_ontologies:
                if bool(ontology.getOntologyID().equals(root_id)):
                    continue  # Crucial: prevent fold validation leakage.
                imported_count += 1
                imported_axioms.addAll(ontology.getAxioms())
            if direct_imports and imported_count == 0:
                raise RuntimeError(
                    "The source declares imports but no imported ontology axioms were loaded"
                )
            if direct_imports and imported_axioms.isEmpty():
                raise RuntimeError("Imported ontologies contain no axioms")
            manager = OWLManager.createOWLOntologyManager()
            frozen = manager.createOntology(imported_axioms)
            temp = IMPORT_SNAPSHOT.with_name("imported_axioms.pending.owl")
            from org.semanticweb.owlapi.formats import RDFXMLDocumentFormat
            manager.saveOntology(
                frozen, RDFXMLDocumentFormat(), IRI.create(temp.resolve().as_uri())
            )
            # Parse using RDFLib to establish that no further imports are required.
            check = Graph()
            check.parse(str(temp), format="xml")
            if any(check.triples((None, OWL.imports, None))):
                raise RuntimeError("Import snapshot unexpectedly declares further imports")
            temp.replace(IMPORT_SNAPSHOT)
            import hashlib
            snapshot_sha256 = hashlib.sha256(IMPORT_SNAPSHOT.read_bytes()).hexdigest()
            write_json(IMPORT_MANIFEST, {
                "cache_schema": 1,
                "snapshot_sha256": snapshot_sha256,
                "direct_import_iris": direct_imports,
                "imported_ontologies": imported_count,
                "imported_axioms": int(imported_axioms.size()),
                "note": "Derived from the full OWLAPI import closure of src/train.ttl; "
                        "training root axioms deliberately excluded"
            })
            print(f"IMPORT CACHE: saved {imported_count} imported ontologies / "
                  f"{imported_axioms.size()} axioms to {IMPORT_SNAPSHOT}", flush=True)
        except Exception as exc:
            # Do not change ontology version or silently drop imports.
            raise RuntimeError(
                "Unable to initialize the import cache. The source ontology's "
                "remote imports could not be loaded. This bootstrap needs one "
                "successful online load; retry when the ontology host is reachable. "
                "Once cached, all training folds and future runs are offline. "
                f"Original error: {exc}"
            ) from exc
    else:
        print(f"IMPORT CACHE: using local snapshot {IMPORT_SNAPSHOT}", flush=True)

    # Read exclusively from disk. The snapshot has no owl:imports statements.
    snapshot = PathDataset(str(IMPORT_SNAPSHOT.resolve()))
    local_axioms = HashSet()
    local_axioms.addAll(snapshot.ontology.getAxioms())
    if direct_imports and local_axioms.isEmpty():
        raise RuntimeError("Import snapshot unexpectedly empty; delete cache to reinitialize")
    _IMPORT_AXIOMS = local_axioms
    _IMPORT_INFO = {
        "snapshot_path": str(IMPORT_SNAPSHOT),
        "imported_axioms": int(local_axioms.size()),
        "direct_import_iris": direct_imports,
        "network_used_for_each_fold": False,
    }
    return _IMPORT_AXIOMS, _IMPORT_INFO


def java_ontology(path):
    """Merge fold-specific axioms with cached imports, WITHOUT network calls."""
    from mowl.datasets.base import PathDataset, Dataset, OWLClasses, OWLObjectProperties, OWLIndividuals
    from mowl.ontology.normalize import ELNormalizer, GCI
    from org.semanticweb.owlapi.apibinding import OWLManager
    from org.semanticweb.owlapi.model import IRI
    from java.util import HashSet

    import_axioms, cache_info = _ensure_import_snapshot()
    local_path = _generate_import_free_root(Path(path))
    # PathDataset on the import-free copy cannot resolve remote ontology URLs.
    root = PathDataset(str(local_path.resolve()))
    manager = OWLManager.createOWLOntologyManager()
    factory = manager.getOWLDataFactory()
    axioms = HashSet()
    axioms.addAll(import_axioms)
    axioms.addAll(root.ontology.getAxioms())
    merged = manager.createOntology(axioms)
    dataset = Dataset(merged)
    norm = ELNormalizer().normalize(merged, use_cache=False)
    class_iris = set(dataset.classes.as_str)
    prop_iris = set(dataset.object_properties.as_str)
    individual_iris = set(dataset.individuals.as_str)
    counts = {}
    for form, items in norm.items():
        counts[form] = len(items)
        if items:
            c, p, i = GCI.get_entities(items)
            class_iris.update(map(str, c))
            prop_iris.update(map(str, p))
            individual_iris.update(map(str, i))
    dataset._classes = OWLClasses([
        factory.getOWLClass(IRI.create(x)) for x in sorted(class_iris)
    ])
    dataset._object_properties = OWLObjectProperties([
        factory.getOWLObjectProperty(IRI.create(x)) for x in sorted(prop_iris)
    ])
    dataset._individuals = OWLIndividuals([
        factory.getOWLNamedIndividual(IRI.create(x)) for x in sorted(individual_iris)
    ])
    return dataset, merged, factory, {
        "import_closure": 1 + json.loads(IMPORT_MANIFEST.read_text(encoding="utf-8")).get("imported_ontologies", 0),
        "materialized_axioms": int(axioms.size()),
        "normalized_counts": counts,
        "indexed_class_iris": len(class_iris),
        "import_cache": cache_info,
    }


def audit_and_infer(ontology, factory, train_pairs, forbidden_pairs, classes,
                    inferred_cap, audit_tag):
    """HermiT entails checks, produces training-only named inferred positives."""
    from org.semanticweb.owlapi.model import IRI
    from org.semanticweb.HermiT import Reasoner
    reasoner = Reasoner.ReasonerFactory().createReasoner(ontology)
    forbidden = set(forbidden_pairs)
    leaks = []
    inferred = set()
    checked = 0
    try:
        if not bool(reasoner.isConsistent()):
            raise RuntimeError(f"{audit_tag} merged training ontology inconsistent")
        for a, b in sorted(forbidden):
            axiom = factory.getOWLSubClassOfAxiom(
                factory.getOWLClass(IRI.create(a)),
                factory.getOWLClass(IRI.create(b)))
            checked += 1
            if bool(reasoner.isEntailed(axiom)):
                leaks.append((a, b))
        if leaks:
            write_json(AUDIT_FILE, {"status": "ENTAILMENT_LEAKAGE",
                                    "stage": audit_tag, "entailed_forbidden_pairs": leaks,
                                    "checked_pairs": checked})
            raise RuntimeError(f"{audit_tag}: {len(leaks)} forbidden subclass pairs entailed")
        for child in sorted(classes):
            owl_child = factory.getOWLClass(IRI.create(child))
            supers = reasoner.getSuperClasses(owl_child, False).getFlattened()
            for parent_cls in supers:
                parent = str(parent_cls.getIRI().toString())
                if (parent != child and parent in classes
                        and parent not in ("http://www.w3.org/2002/07/owl#Thing",
                                           "http://www.w3.org/2002/07/owl#Nothing")
                        and (child, parent) not in forbidden):
                    inferred.add((child, parent))
    finally:
        reasoner.dispose()
    inferred -= set(train_pairs)
    # Deterministic global cap to control how strongly superclass hubs dominate.
    inferred = sorted(inferred)[:inferred_cap]
    return inferred, {"stage": audit_tag, "status": "PASS", "checked_pairs": checked,
                      "forbidden_entailed": 0, "new_inferred_training_pairs": len(inferred)}


