def pretrained_features(iri_order, texts, model_name, batch_size):
    try:
        from sentence_transformers import SentenceTransformer
    except ImportError as exc:
        raise RuntimeError(
            'Pretrained semantic encoder required. Install inside .venv-mowl: '
            'python -m pip install sentence-transformers'
        ) from exc
    descriptions = []
    described = 0
    for iri in iri_order:
        literal = texts.get(iri, '').strip()
        if literal:
            described += 1
        # The opaque ontology identifier is not treated as a meaningful word.
        descriptions.append(literal or 'ontology class with no available definition')
    print(f'Pretrained semantic texts: {described}/{len(iri_order)}', flush=True)
    print('SentenceTransformer model:', model_name, flush=True)
    try:
        encoder = SentenceTransformer(model_name, device='cpu')
        array = encoder.encode(
            descriptions, batch_size=batch_size, show_progress_bar=True,
            convert_to_numpy=True, normalize_embeddings=True
        )
    except Exception as exc:
        raise RuntimeError(
            f'Could not load or encode pretrained model {model_name!r}; '
            'initial use requires internet access and enough disk space'
        ) from exc
    features = torch.as_tensor(np.array(array, copy=True), dtype=torch.float32)
    if features.ndim != 2 or features.shape[0] != len(iri_order):
        raise RuntimeError('Unexpected SentenceTransformer embedding matrix shape')
    if not bool(torch.isfinite(features).all().item()):
        raise RuntimeError('Nonfinite pretrained semantic vectors')
    return F.normalize(features, dim=1), described


def imported_annotation_text(ontology, iris):
    """Read annotation literals from OWLAPI materialized imports.

    This avoids assigning the same missing-text placeholder to hundreds of
    imported classes whose labels are available in their OWL documents.
    """
    from org.semanticweb.owlapi.model import IRI
    result = defaultdict(list)
    predicates = ('label', 'preflabel', 'definition', 'description',
                  'elucidation', 'comment')
    for iri in iris:
        for axiom in ontology.getAnnotationAssertionAxioms(IRI.create(iri)):
            prop = str(axiom.getProperty().getIRI().toString()).lower()
            if not any(word in prop for word in predicates):
                # IAO:0000115 is the widely used definition property.
                if not prop.endswith('iao_0000115'):
                    continue
            optional = axiom.getValue().asLiteral()
            if optional.isPresent():
                value = str(optional.get().getLiteral()).strip()
                if value:
                    result[iri].append(value)
    return {iri: ' '.join(parts) for iri, parts in result.items()}


def save_training_graph(original, withheld, destination):
    g = Graph()
    for prefix, ns in original.namespace_manager.namespaces():
        g.bind(prefix, ns)
    for triple in original:
        g.add(triple)
    for child, parent in withheld:
        g.remove((URIRef(child), RDFS.subClassOf, URIRef(parent)))
    if set(named_pairs(g)) & set(withheld):
        raise RuntimeError('Fold-masked asserted subclass axioms remain in graph')
    if declarations(original) - declarations(g):
        raise RuntimeError('Fold graph lost declarations')
    destination.parent.mkdir(parents=True, exist_ok=True)
    g.serialize(destination=str(destination), format='turtle')


def fold_edges(train_pairs, count, seed):
    """Balanced across asserted parent groups without using outer labels."""
    rng = random.Random(seed)
    by_parent = defaultdict(list)
    for pair in train_pairs:
        by_parent[pair[1]].append(pair)
    folds = [set() for _ in range(count)]
    for parent in sorted(by_parent):
        edges = list(by_parent[parent])
        rng.shuffle(edges)
        offset = rng.randrange(count)
        for n, edge in enumerate(edges):
            folds[(offset + n) % count].add(edge)
    if set.union(*folds) != set(train_pairs):
        raise RuntimeError('Crossfit partition does not cover all training pairs')
    if any(not fold for fold in folds):
        raise RuntimeError('Crossfit fold is empty; reduce --folds')
    return [sorted(fold) for fold in folds]


def make_native_model(path, dimension, epochs, model_path, forbidden_pairs, audit_label):
    """Materialize the full import closure, audit leakage, train native mOWL."""
    dataset, ontology, factory, ontology_info = java_ontology(path)
    from org.semanticweb.owlapi.model import IRI
    from org.semanticweb.HermiT import Reasoner
    reasoner = Reasoner.ReasonerFactory().createReasoner(ontology)
    leaked = []
    try:
        if not bool(reasoner.isConsistent()):
            raise RuntimeError(f'{audit_label}: training ontology inconsistent')
        for child, parent in sorted(set(forbidden_pairs)):
            axiom = factory.getOWLSubClassOfAxiom(
                factory.getOWLClass(IRI.create(child)),
                factory.getOWLClass(IRI.create(parent))
            )
            if bool(reasoner.isEntailed(axiom)):
                leaked.append((child, parent))
    finally:
        reasoner.dispose()
    if leaked:
        write_json(AUDIT_FILE, {
            'status': 'ENTAILMENT_LEAKAGE', 'stage': audit_label,
            'entailed_forbidden_pairs': leaked,
            'checked_pairs': len(set(forbidden_pairs))
        })
        raise RuntimeError(
            f'{audit_label}: {len(leaked)} held-out edges entailed from imports; '
            'see reports/mowl_import_leakage.json'
        )
    from mowl.models import ELEmbeddings
    model = ELEmbeddings(
        dataset, embed_dim=dimension, margin=0.1, reg_norm=1.0,
        learning_rate=0.001, batch_size=128,
        model_filepath=str(model_path), device='cpu'
    )
    print(f'{audit_label}: native ELEmbeddings {epochs} epochs; '
          f'import closure={ontology_info["import_closure"]}', flush=True)
    model.train(epochs=epochs, validate_every=epochs)
    index = {str(iri): int(idx) for iri, idx in model.class_index_dict.items()}
    centers = model.module.class_embed.weight.detach().cpu().clone()
    if not bool(torch.isfinite(centers).all().item()):
        raise RuntimeError(f'{audit_label}: native embeddings nonfinite')
    return model, index, centers, ontology_info


def align_native_to_text(centers, native_index, iris, text_features, ridge=0.5):
    """Unsupervised ridge mapping of geometric class centers into text space.

    This uses class identity / pretrained text alone; NO subclass labels.
    Separate mOWL runs have different orientations, so a shared alignment is
    necessary for cross-fitted masked reconstruction.
    """
    rows = [idx for idx, iri in enumerate(iris) if iri in native_index]
    a = F.normalize(
        centers[[native_index[iris[i]] for i in rows]], dim=1
    )
    b = text_features[rows]
    weights = torch.linalg.solve(
        a.T @ a + ridge * torch.eye(a.shape[1]), a.T @ b
    )
    result = torch.empty_like(text_features)
    result[:] = text_features
    result[rows] = F.normalize(a @ weights, dim=1)
    return result


class SemanticPrototypeAdapter(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.mapping = nn.Linear(dim, dim, bias=False)
        nn.init.zeros_(self.mapping.weight)

    def forward(self, features, native_aligned, native_weight):
        adapted = F.normalize(features + self.mapping(features), dim=1)
        return F.normalize(
            (1.0 - native_weight) * adapted + native_weight * native_aligned,
            dim=1
        )


def class_pairs_to_ids(pairs, index, label):
    missing = {iri for edge in pairs for iri in edge if iri not in index}
    if missing:
        raise RuntimeError(f'{label}: missing class IRIs: {sorted(missing)[:5]}')
    return torch.tensor([(index[a], index[b]) for a, b in pairs], dtype=torch.long)


def scored_rows(matrix, pairs, index, stage):
    if not pairs:
        return []
    ids = class_pairs_to_ids(pairs, index, stage)
    with torch.no_grad():
        vals = (matrix[ids[:, 0]] * matrix[ids[:, 1]]).sum(1)
    return [
        {'child_iri': child, 'parent_iri': parent,
         'cosine_similarity': float(score), 'stage': stage}
        for (child, parent), score in zip(pairs, vals.detach().cpu().tolist())
    ]


def describe_rows(rows):
    values = [row['cosine_similarity'] for row in rows]
    return {'count': len(values), 'mean': float(np.mean(values)) if values else None,
            'minimum': min(values) if values else None,
            'maximum': max(values) if values else None,
            'at_or_above_0_60': sum(x >= 0.60 for x in values),
            'at_or_above_0_70': sum(x >= 0.70 for x in values)}


def make_controls(all_iris, known, count, seed):
    rng = random.Random(seed)
    blocked = set(known)
    found = set()
    for _ in range(count * 100):
        if len(found) >= count:
            break
        a, b = rng.sample(all_iris, 2)
        if (a, b) not in blocked:
            found.add((a, b))
    return sorted(found)


def prototypes_from_support(support_pairs, global_index):
    """Return parent -> ids of other known children in this fold's graph."""
    support = defaultdict(set)
    for child, parent in support_pairs:
        if child in global_index and parent in global_index:
            support[global_index[parent]].add(global_index[child])
    return {k: sorted(v) for k, v in support.items()}


def masked_loss(vectors, target_pairs, support_by_parent, index,
                hard_alpha, prototype_mix, preservation, text_features):
    """Mask each target edge from superclass support; maximize held-out cosine.

    The *native* inputs are also cross-fitted and do not contain target edges.
    """
    ids = class_pairs_to_ids(target_pairs, index, 'masked reconstruction')
    children, parents = ids[:, 0], ids[:, 1]
    direct = (vectors[children] * vectors[parents]).sum(1)
    prototypes = []
    for child, parent in ids.tolist():
        # The target child never contributes to its own prototype.
        other_children = [i for i in support_by_parent.get(parent, ()) if i != child]
        if other_children:
            group = F.normalize(vectors[other_children].mean(0), dim=0)
            prototype = F.normalize(
                (1.0 - prototype_mix) * vectors[parent] + prototype_mix * group,
                dim=0
            )
        else:
            prototype = vectors[parent]
        prototypes.append(prototype)
    proto = torch.stack(prototypes)
    similarities = (vectors[children] * proto).sum(1)
    # Hardness is determined from masked predictions, not outer validation.
    hardness = (1 + hard_alpha * (1 - similarities.detach()).square()).clamp(max=10)
    loss = (hardness * (1 - similarities).square()).mean()
    loss += 0.35 * (1 - direct).square().mean()
    # Prevent trivial all-class collapse / catastrophic semantic drift.
    loss += preservation * (1 - (vectors * text_features).sum(1)).mean()
    return loss, direct.mean().detach(), similarities.mean().detach()


def fit_adapter(fold_records, base, config, epochs, seed):
    torch.manual_seed(seed)
    adapter = SemanticPrototypeAdapter(base.shape[1])
    optimizer = torch.optim.AdamW(
        adapter.parameters(), lr=config['adapter_lr'], weight_decay=1e-4
    )
    best_loss = float('inf')
    best_state = None
    # Each training fold's target edges are absent from its native model.
    for epoch in range(epochs):
        adapter.train()
        optimizer.zero_grad()
        fold_losses = []
        for record in fold_records:
            vectors = adapter(base, record['aligned_native'], config['native_weight'])
            loss, _, _ = masked_loss(
                vectors, record['masked_pairs'], record['support'], record['index'],
                config['hard_alpha'], config['prototype_mix'],
                config['preservation'], base
            )
            fold_losses.append(loss)
        loss = torch.stack(fold_losses).mean()
        if not bool(torch.isfinite(loss).item()):
            raise RuntimeError('Nonfinite masked-prototype loss')
        loss.backward()
        nn.utils.clip_grad_norm_(adapter.parameters(), 3.0)
        optimizer.step()
        value = float(loss.detach())
        if value < best_loss:
            best_loss = value
            best_state = {k: v.detach().clone() for k, v in adapter.state_dict().items()}
    adapter.load_state_dict(best_state)
    adapter.eval()
    return adapter, best_loss


def crossfit_records(graph, pairs, forbidden_outer, global_index,
                     iris, text_features, args, tag, native_epochs):
    """Train K native models with each target fold removed from its graph."""
    folds = fold_edges(pairs, args.folds, args.seed + (0 if tag == 'inner' else 100))
    records = []
    audits = []
    for fold_no, masked in enumerate(folds, 1):
        stage = f'{tag}_fold_{fold_no}'
        support = sorted(set(pairs) - set(masked))
        path = OUT / f'mowl_{stage}_training.ttl'
        save_training_graph(graph, masked, path)
        model, model_index, centers, meta = make_native_model(
            path, args.native_dimension, native_epochs,
            OUT / f'mowl_{stage}_native.pt',
            sorted(set(forbidden_outer) | set(masked)), stage
        )
        native_aligned = align_native_to_text(
            centers, model_index, iris, text_features,
            ridge=args.native_ridge
        )
        records.append({
            'stage': stage, 'masked_pairs': masked,
            'support': prototypes_from_support(support, global_index),
            'aligned_native': native_aligned, 'index': global_index,
        })
        audits.append({'stage': stage, 'masked_count': len(masked),
                       'imports': meta, 'forbidden_entailed': 0})
        del model, centers
    return records, audits


def validate_config(adapter, base, aligned, eval_pairs, controls, index, config, stage):
    with torch.no_grad():
        vectors = adapter(base, aligned, config['native_weight'])
    rows = scored_rows(vectors, eval_pairs, index, stage)
    control_rows = scored_rows(vectors, controls, index, stage + '_controls')
    validation = describe_rows(rows)
    control = describe_rows(control_rows)
    gap = validation['mean'] - control['mean'] if control['mean'] is not None else None
    return vectors, rows, control_rows, validation, control, gap


def choose_tau(rows):
    mean = describe_rows(rows)['mean']
    grid = [
        {'tau': round(i / 100, 2),
         'retained': sum(row['cosine_similarity'] >= i / 100 for row in rows)}
        for i in range(60, 81)
    ]
    selected = next((row['tau'] for row in grid if mean is not None
                     and mean >= 0.70 and row['retained'] > 0), None)
    return selected, grid


